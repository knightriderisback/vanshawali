/* ── i18n Engine ── */
let CURRENT_LANG = localStorage.getItem('vanshawali-lang') || 'hi';

function t(key) {
  return (TRANSLATIONS[CURRENT_LANG] && TRANSLATIONS[CURRENT_LANG][key]) || TRANSLATIONS.hi[key] || key;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  // App title
  document.title = t('appTitle') + ' — 3D Family Tree';
  // Update lang flag
  const flagEl = document.getElementById('lang-flag');
  if (flagEl) flagEl.textContent = TRANSLATIONS[CURRENT_LANG].flag || '🌐';
  // Update active lang in dropdown
  document.querySelectorAll('.lang-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.lang === CURRENT_LANG);
  });
}
